-- =====================================================================
-- Módulo de importaciones (IMP_) para ONIX · samya_almacen_cbba
-- Motor: MySQL 5.5.60. Solo en COCHABAMBA (allí se pide). Santa Cruz se
-- lee para stock y ventas mediante vistas (mismo servidor).
-- Requiere 01_catalogo_producto_proveedor.sql (PROVEEDOR con prefijo,
-- lead time e incoterm; PRODUCTO con COD_PROVEEDOR y ESTADO_FORECAST).
--
-- Mismo modelo que el prototipo (supabase/migrations/202611110008):
--   proforma → factura → asignación → embarque → recepción (COMPRA de ONIX)
--   anticipo por proforma → aplicación a facturas; cancelación por factura
--   gastos con % al costo sugerido y corregible → hoja de costos por lote
--   corrida de forecast → proforma sugerida
--
-- MySQL 5.5: sin CHECK (las reglas van en triggers con SIGNAL), sin
-- columnas generadas, un solo TIMESTAMP con CURRENT_TIMESTAMP por tabla,
-- un trigger por evento y tabla, y vistas sin subconsultas en el FROM.
-- Ejecutar con el cliente mysql (se detiene ante el primer error) y
-- probar SIEMPRE antes en una copia.
-- =====================================================================
