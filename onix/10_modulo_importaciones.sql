CREATE VIEW V_IMP_FACTURA_TOTAL AS
SELECT fd.COD_FACTURA, SUM(fd.CANTIDAD * fd.PRECIO_UNITARIO) AS TOTAL_MONEDA,
       MIN(fd.PRECIO_UNITARIO IS NOT NULL) AS PRECIOS_COMPLETOS
FROM IMP_FACTURA_DETALLE fd GROUP BY fd.COD_FACTURA;

CREATE VIEW V_IMP_ANTICIPO_FACTURA AS
SELECT gf.COD_FACTURA, SUM(gf.IMPORTE) AS IMPORTE, SUM(gf.IMPORTE * g.TIPO_CAMBIO) AS IMPORTE_BS,
       MIN(g.TIPO_CAMBIO IS NOT NULL) AS CON_TC
FROM IMP_GIRO_FACTURA gf JOIN IMP_GIRO g ON g.COD_GIRO = gf.COD_GIRO GROUP BY gf.COD_FACTURA;

CREATE VIEW V_IMP_CANCELACION_FACTURA AS
SELECT g.COD_FACTURA, SUM(g.IMPORTE) AS IMPORTE, SUM(g.IMPORTE * g.TIPO_CAMBIO) AS IMPORTE_BS,
       MIN(g.TIPO_CAMBIO IS NOT NULL) AS CON_TC
FROM IMP_GIRO g WHERE g.TIPO = 'cancelacion' GROUP BY g.COD_FACTURA;

CREATE VIEW V_IMP_PAGO_FACTURA AS
SELECT f.COD_FACTURA, f.NUMERO, f.COD_PROVEEDOR, IFNULL(f.IMPORTE, t.TOTAL_MONEDA) AS IMPORTE,
       IFNULL(a.IMPORTE,0) AS ANTICIPOS_APLICADOS, IFNULL(c.IMPORTE,0) AS CANCELADO,
       IFNULL(a.IMPORTE,0) + IFNULL(c.IMPORTE,0) AS PAGADO,
       IFNULL(f.IMPORTE, t.TOTAL_MONEDA) - IFNULL(a.IMPORTE,0) - IFNULL(c.IMPORTE,0) AS SALDO,
       IF(IFNULL(a.CON_TC,1) AND IFNULL(c.CON_TC,1), IFNULL(a.IMPORTE_BS,0) + IFNULL(c.IMPORTE_BS,0), NULL) AS PAGADO_BS
FROM IMP_FACTURA f
LEFT JOIN V_IMP_FACTURA_TOTAL t ON t.COD_FACTURA = f.COD_FACTURA
LEFT JOIN V_IMP_ANTICIPO_FACTURA a ON a.COD_FACTURA = f.COD_FACTURA
LEFT JOIN V_IMP_CANCELACION_FACTURA c ON c.COD_FACTURA = f.COD_FACTURA;

CREATE VIEW V_IMP_GASTO_FACTURA AS
SELECT g.COD_FACTURA,
       SUM(IF(gr.ES_VALOR_FACTURA = 1, g.IMPORTE_BS, 0)) AS DIF_CAMBIO_BS,
       SUM(IF(gr.ES_VALOR_FACTURA = 0, g.IMPORTE_BS, 0)) AS GASTOS_BS,
       SUM(IF(gr.ES_VALOR_FACTURA = 0, g.IMPORTE_COSTO_BS, 0)) AS GASTOS_COSTO_BS
FROM IMP_GASTO g JOIN IMP_CONCEPTO_GASTO c ON c.COD_CONCEPTO = g.COD_CONCEPTO
JOIN IMP_GRUPO_GASTO gr ON gr.COD_GRUPO = c.COD_GRUPO GROUP BY g.COD_FACTURA;

-- CIF en Bs = lo pagado en Bs + diferencia de cambio (factura pagada al 99 % o más),
-- o lo pagado + el saldo al TC manual. Paramétrica = (CIF Bs + gastos al costo) / CIF Bs.
CREATE VIEW V_IMP_COSTEO_BASE AS
SELECT f.COD_FACTURA, f.NUMERO, f.COD_COMPRA, c.COD_COSTEO, c.ESTADO, c.CONDICION_ENTREGA, c.TC_DIM,
       t.TOTAL_MONEDA, p.PAGADO, p.PAGADO_BS, IFNULL(gf.DIF_CAMBIO_BS,0) AS DIF_CAMBIO_BS,
       IFNULL(gf.GASTOS_BS,0) AS GASTOS_BS, IFNULL(gf.GASTOS_COSTO_BS,0) AS GASTOS_COSTO_BS,
       CASE WHEN c.TIPO_CAMBIO_MANUAL IS NOT NULL
              THEN IFNULL(p.PAGADO_BS,0) + GREATEST(t.TOTAL_MONEDA - IFNULL(p.PAGADO,0), 0) * c.TIPO_CAMBIO_MANUAL + IFNULL(gf.DIF_CAMBIO_BS,0)
            WHEN p.PAGADO_BS IS NOT NULL AND p.PAGADO > 0 AND p.PAGADO >= t.TOTAL_MONEDA * 0.99
              THEN p.PAGADO_BS + IFNULL(gf.DIF_CAMBIO_BS,0) END AS CIF_BS
FROM IMP_FACTURA f
LEFT JOIN IMP_COSTEO c ON c.COD_FACTURA = f.COD_FACTURA
LEFT JOIN V_IMP_FACTURA_TOTAL t ON t.COD_FACTURA = f.COD_FACTURA
LEFT JOIN V_IMP_PAGO_FACTURA p ON p.COD_FACTURA = f.COD_FACTURA
LEFT JOIN V_IMP_GASTO_FACTURA gf ON gf.COD_FACTURA = f.COD_FACTURA;

CREATE VIEW V_IMP_COSTEO AS
SELECT b.*, IF(b.TOTAL_MONEDA > 0 AND b.CIF_BS > 0, b.CIF_BS / b.TOTAL_MONEDA, NULL) AS TC_EFECTIVO,
       IF(b.CIF_BS > 0, (b.CIF_BS + b.GASTOS_COSTO_BS) / b.CIF_BS, NULL) AS PARAMETRICA,
       IF(b.CIF_BS > 0, b.CIF_BS + b.GASTOS_COSTO_BS, NULL) AS COSTO_TOTAL_BS
FROM V_IMP_COSTEO_BASE b;

CREATE VIEW V_IMP_COSTO_LOTE AS
SELECT fd.COD_FACTURA, fd.COD_FD, fd.LINEA, fd.COD_PRODUCTO, pr.CODIGO, pr.NOMBRE,
       cd.LOTE, cd.VENCIMIENTO, cd.COD_DETALLE, IFNULL(cd.CANTIDAD, fd.CANTIDAD) AS CANTIDAD, fd.PRECIO_UNITARIO,
       fd.PRECIO_UNITARIO * c.TC_EFECTIVO AS COSTO_UNITARIO_ORIGEN_BS,
       fd.PRECIO_UNITARIO * c.TC_EFECTIVO * c.PARAMETRICA AS COSTO_UNITARIO_BS,
       IFNULL(cd.CANTIDAD, fd.CANTIDAD) * fd.PRECIO_UNITARIO * c.TC_EFECTIVO * c.PARAMETRICA AS COSTO_TOTAL_BS
FROM IMP_FACTURA_DETALLE fd
JOIN PRODUCTO pr ON pr.COD_PRODUCTO = fd.COD_PRODUCTO
JOIN V_IMP_COSTEO c ON c.COD_FACTURA = fd.COD_FACTURA
LEFT JOIN IMP_COSTEO_DETALLE cd ON cd.COD_FD = fd.COD_FD;

-- Planificación. Stock: PRODUCTO.STOCK de cada sucursal (mismo servidor), unido por CODIGO.
