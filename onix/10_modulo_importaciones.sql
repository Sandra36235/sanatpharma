-- Ventas por mes y sucursal: egresos de kardex ligados a una nota de venta.
-- Confirmar con Sistemas qué ESTADO de NOTA/KARDEX_EGRESO cuenta como venta válida.
CREATE VIEW V_IMP_VENTA_MES_CBBA AS
SELECT ki.COD_PRODUCTO, DATE_FORMAT(ke.FECHA, '%Y-%m-01') AS MES, SUM(ke.CANTIDAD) AS CANTIDAD
FROM KARDEX_EGRESO ke JOIN KARDEX_INGRESO ki ON ki.COD_KI = ke.COD_KI
WHERE ke.COD_NOTA IS NOT NULL AND ke.FECHA IS NOT NULL
GROUP BY ki.COD_PRODUCTO, DATE_FORMAT(ke.FECHA, '%Y-%m-01');
CREATE VIEW V_IMP_VENTA_MES_SCZ AS
SELECT pc.COD_PRODUCTO, DATE_FORMAT(ke.FECHA, '%Y-%m-01') AS MES, SUM(ke.CANTIDAD) AS CANTIDAD
FROM samya_almacen_scz.KARDEX_EGRESO ke
JOIN samya_almacen_scz.KARDEX_INGRESO ki ON ki.COD_KI = ke.COD_KI
JOIN samya_almacen_scz.PRODUCTO ps ON ps.COD_PRODUCTO = ki.COD_PRODUCTO
JOIN PRODUCTO pc ON pc.CODIGO = ps.CODIGO
WHERE ke.COD_NOTA IS NOT NULL AND ke.FECHA IS NOT NULL
GROUP BY pc.COD_PRODUCTO, DATE_FORMAT(ke.FECHA, '%Y-%m-01');
CREATE VIEW V_IMP_VENTA_MES AS
SELECT COD_PRODUCTO, MES, CANTIDAD, 'COCHABAMBA' AS SUCURSAL FROM V_IMP_VENTA_MES_CBBA
UNION ALL
SELECT COD_PRODUCTO, MES, CANTIDAD, 'SANTA CRUZ' FROM V_IMP_VENTA_MES_SCZ;

-- Pronóstico mensual: PESO_RECIENTE × promedio 3 meses + resto × promedio de MESES_HISTORIA
-- (meses completos antes del mes actual).
CREATE VIEW V_IMP_PRONOSTICO AS
SELECT v.COD_PRODUCTO,
       SUM(IF(v.MES >= DATE_SUB(DATE_FORMAT(CURDATE(),'%Y-%m-01'), INTERVAL 3 MONTH), v.CANTIDAD, 0)) / 3 AS PROM_3,
       SUM(v.CANTIDAD) / (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'MESES_HISTORIA') AS PROM_HIST
FROM V_IMP_VENTA_MES v
WHERE v.MES < DATE_FORMAT(CURDATE(),'%Y-%m-01')
  AND v.MES >= DATE_SUB(DATE_FORMAT(CURDATE(),'%Y-%m-01'),
                        INTERVAL (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'MESES_HISTORIA') MONTH)
GROUP BY v.COD_PRODUCTO;

-- En camino: pedido vigente en proformas enviadas/confirmadas menos lo recibido.
CREATE VIEW V_IMP_RECIBIDO_PD AS
SELECT a.COD_PD, SUM(rd.CANTIDAD) AS RECIBIDO
FROM IMP_RECEPCION_DETALLE rd JOIN IMP_ASIGNACION a ON a.COD_ASIGNACION = rd.COD_ASIGNACION GROUP BY a.COD_PD;
CREATE VIEW V_IMP_EN_CAMINO AS
SELECT pd.COD_PRODUCTO, SUM(GREATEST(pd.CANTIDAD - pd.CANTIDAD_CANCELADA - IFNULL(r.RECIBIDO,0), 0)) AS EN_CAMINO
FROM IMP_PROFORMA_DETALLE pd JOIN IMP_PROFORMA p ON p.COD_PROFORMA = pd.COD_PROFORMA
LEFT JOIN V_IMP_RECIBIDO_PD r ON r.COD_PD = pd.COD_PD
WHERE p.ESTADO IN ('enviada','confirmada') GROUP BY pd.COD_PRODUCTO;

