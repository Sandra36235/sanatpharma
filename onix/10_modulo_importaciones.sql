SELECT p.COD_PRODUCTO, p.CODIGO, p.CODIGO_NUEVO, p.NOMBRE, pp.COD_PROVEEDOR, pp.MIN_PEDIDO, pp.UNIDADES_CAJA,
       IFNULL(IFNULL(pp.LEAD_TIME_DIAS, v.LEAD_TIME_DIAS), (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'LEAD_TIME_DEFECTO')) AS LEAD_TIME_DIAS,
       s.STOCK_CBBA, s.STOCK_SCZ, s.STOCK_TOTAL, IFNULL(c.EN_CAMINO,0) AS EN_CAMINO,
       (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'PESO_RECIENTE') * IFNULL(f.PROM_3,0)
         + (1 - (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'PESO_RECIENTE')) * IFNULL(f.PROM_HIST,0) AS PRONOSTICO_MENSUAL
FROM PRODUCTO p
JOIN V_IMP_STOCK s ON s.COD_PRODUCTO = p.COD_PRODUCTO
LEFT JOIN PRODUCTO_PROVEEDOR pp ON pp.COD_PRODUCTO = p.COD_PRODUCTO AND pp.HABITUAL = 1
LEFT JOIN PROVEEDOR v ON v.COD_PROVEEDOR = pp.COD_PROVEEDOR
LEFT JOIN V_IMP_EN_CAMINO c ON c.COD_PRODUCTO = p.COD_PRODUCTO
LEFT JOIN V_IMP_PRONOSTICO f ON f.COD_PRODUCTO = p.COD_PRODUCTO
WHERE p.ESTADO_FORECAST = 1;

CREATE VIEW V_IMP_ALERTA AS
SELECT b.*, b.PRONOSTICO_MENSUAL / 30 AS VENTA_DIARIA,
       b.PRONOSTICO_MENSUAL / 30 * (b.LEAD_TIME_DIAS + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_SEGURIDAD')) AS PUNTO_PEDIDO,
       GREATEST(b.PRONOSTICO_MENSUAL / 30 * (b.LEAD_TIME_DIAS + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_SEGURIDAD')
                + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_COBERTURA')) - b.STOCK_TOTAL - b.EN_CAMINO, 0) AS NECESIDAD,
       CASE WHEN b.PRONOSTICO_MENSUAL <= 0 THEN 'SIN VENTAS'
            WHEN b.STOCK_TOTAL + b.EN_CAMINO <= b.PRONOSTICO_MENSUAL / 30 * (b.LEAD_TIME_DIAS + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_SEGURIDAD')) THEN 'PEDIR YA'
            WHEN b.STOCK_TOTAL + b.EN_CAMINO <= b.PRONOSTICO_MENSUAL / 30 * (b.LEAD_TIME_DIAS + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_SEGURIDAD')
                 + (SELECT VALOR FROM IMP_PARAMETRO WHERE CLAVE = 'DIAS_AVISO')) THEN 'PEDIR PRONTO'
            ELSE 'CUBIERTO' END AS ALERTA
FROM V_IMP_PLAN_BASE b;
