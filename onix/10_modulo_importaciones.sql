DELIMITER ;;
CREATE TRIGGER IMP_PROFORMA_BI BEFORE INSERT ON IMP_PROFORMA FOR EACH ROW
BEGIN
  IF NEW.ESTADO NOT IN ('sugerida','enviada','confirmada','cerrada','anulada') THEN
